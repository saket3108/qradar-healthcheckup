"""QRadar-specific recommendation library.

Every finding code maps to: description, impact, business impact, risk, recommendation steps, IBM best
practice and default priority.  Notification text is matched with ``patterns`` (regex, case-insensitive).
The wording follows IBM QRadar Administration / Tuning guidance and common Support (TS) practice; version
specific commands are indicated generically so they remain valid across 7.4.x / 7.5.x.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field


@dataclass(frozen=True)
class KBEntry:
    code: str
    category: str          # deployment|notifications|logsources|applications|performance|licensing|wincollect
    title: str
    description: str
    impact: str
    business_impact: str
    risk: str
    recommendation: tuple[str, ...]
    best_practice: str
    priority: str = "P2"   # P1 (immediate) .. P4
    severity: str = "medium"
    domain: str = ""       # EPS|FPM|Parsing|DSM|WinCollect|Application|Storage|HA|Performance|Search|CRE|Offense|Deployment|License|Backup
    patterns: tuple[str, ...] = field(default_factory=tuple)

    def regexes(self) -> list[re.Pattern[str]]:
        return [re.compile(p, re.I) for p in self.patterns]


def _e(**kw) -> KBEntry:
    kw["recommendation"] = tuple(kw["recommendation"])
    kw["patterns"] = tuple(kw.get("patterns", ()))
    return KBEntry(**kw)


