BY_CODE: dict[str, KBEntry] = {e.code: e for e in ENTRIES}
_COMPILED: list[tuple[KBEntry, list[re.Pattern[str]]]] = [(e, e.regexes()) for e in ENTRIES if e.patterns]


def get(code: str) -> KBEntry:
    return BY_CODE[code]


def match_notification(text: str) -> KBEntry | None:
    """Best KB match for free-text notification (most specific = most pattern hits)."""
    best: tuple[int, KBEntry] | None = None
    for entry, rxs in _COMPILED:
        hits = sum(1 for rx in rxs if rx.search(text))
        if hits and (best is None or hits > best[0]):
            best = (hits, entry)
    return best[1] if best else None


def categories_summary() -> dict[str, int]:
    out: dict[str, int] = {}
    for e in ENTRIES:
        out[e.domain] = out.get(e.domain, 0) + 1
    return out
